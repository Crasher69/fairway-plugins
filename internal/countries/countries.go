// Name — название страны для имени прокси; неизвестный код остаётся
// кодом.
func Name(code string) string {
	code = strings.ToUpper(code)
	if code == "" {
		return ""
	}
	if name, ok := RU[code]; ok {
		return name
	}
	return code
}
